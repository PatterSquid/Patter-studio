# Makes src/gfonts.js: the Google Fonts library as a compact list for the font picker (family, Fontsource id, kind,
# weights, italic), from google-font-metadata (cdn.jsdelivr.net/npm/google-font-metadata@6.0.8/data/google-fonts-v2.json).
# Fonts download on demand from cdn.jsdelivr.net/fontsource (the same files, OFL or Apache licences, free for any use).
import json, sys
src = sys.argv[1] if len(sys.argv) > 1 else 'google-fonts-v2.json'
d = json.load(open(src)); out = []
K = {'display': 'd', 'sans-serif': 's', 'serif': 'r', 'handwriting': 'h', 'monospace': 'm'}
for k, v in sorted(d.items(), key=lambda kv: kv[1]['family'].lower()):
    if 'latin' not in v.get('subsets', []): continue
    w = sorted(int(x) for x in v.get('weights', []) if str(x).isdigit())
    if not w: continue
    out.append([v['family'], v['id'] if v['id'] != v['family'].lower().replace(' ', '-') else '', K.get(v.get('category'), 's'), ''.join('%d' % (x // 100) for x in w), 1 if 'italic' in v.get('styles', []) else 0])
js = '/* Generated by dev/fontlist.py from google-font-metadata 6.0.8: [family, fontsource id if not the usual, kind (d display, s sans, r serif, h handwriting, m mono), weights in hundreds, has italic] */\nconst GFONTS = ' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n'
open('src/gfonts.js', 'w').write(js); print(len(out), 'fonts,', len(js) // 1024, 'KB')
